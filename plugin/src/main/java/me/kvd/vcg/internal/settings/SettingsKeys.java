package me.kvd.vcg.internal.settings;

import me.kvd.configra.ConfigKeyDeclaration;
import me.kvd.configra.PropertyKey;
import me.kvd.vcg.api.rules.PlatformBorderPattern;
import org.bukkit.Material;
import org.bukkit.block.Biome;

/**
 * Declarations of every configuration option supported by the plugin.
 * <p>
 * Each constant combines a human-readable comment (written verbatim into the
 * generated {@code settings.ini}) with a {@link PropertyKey} that describes
 * the fully-qualified path, the value type and the default value of the
 * option. The declarations in this enum are the single source of truth used
 * by {@link SettingsDefaults} when generating a fresh configuration file and
 * by {@link SettingsLoader} when reading it back.
 *
 * @see SettingsDefaults
 * @see SettingsLoader
 * @see ConfigKeyDeclaration
 */
public enum SettingsKeys implements ConfigKeyDeclaration {

  /**
   * Biome assigned to every chunk generated by this plugin.
   * <p>
   * A biome decides things like grass color, weather and which mobs can spawn
   * there. Expects a valid {@link Biome} name in {@code UPPER_SNAKE_CASE}.
   *
   * @see Biome
   */
  BIOME(
    """
      The biome assigned to every chunk generated by this plugin.
      The biome decides: grass/leaf color, weather (rain/snow),
      and which mobs can spawn there.

      Value type: text (biome name).
      Format: UPPER_SNAKE_CASE, exactly as in Bukkit (uppercase letters,
              underscores instead of spaces).
      Examples of valid values: OCEAN, PLAINS, DESERT, THE_VOID,
                                SNOWY_TUNDRA, NETHER_WASTES
      Full list: https://hub.spigotmc.org/javadocs/bukkit/org/bukkit/block/Biome.html

      Default value: OCEAN
      Note: an invalid name = default value.
      """,
    PropertyKey.string("general.biome", "OCEAN")
  ),

  /**
   * Whether the spawn platform should be generated at all.
   * <p>
   * When {@code false}, the world is left as pure void with no platform of
   * any kind.
   */
  PLATFORM_ENABLED(
    """
      Whether to generate the spawn platform at all.

      true  = the platform is generated (according to settings below)
      false = NOTHING is generated - pure void, zero blocks

      Default value: true
      """,
    PropertyKey.bool("platform.enabled", true)
  ),

  /**
   * Y level (height) at which the platform is placed.
   */
  PLATFORM_Y(
    """
      The height (Y level) at which the platform is placed.

      Value type: integer.
      Range: from 0 (world bottom) to world top (usually 255 or 319
              depending on the Minecraft version).

      64  = classic sea level (most common choice)
      0   = world bottom
      100 = high in the air

      Default value: 64
      """,
    PropertyKey.integer("platform.y", 64)
  ),

  /**
   * Radius, in chunks, of the area covered by the platform around the center
   * chunk.
   * <p>
   * A value of {@code 0} restricts the platform to the center chunk; a value
   * of {@code 1} covers a 3&times;3 chunk area.
   */
  PLATFORM_CHUNK_RADIUS(
    """
      How many chunks in each direction from the center chunk
      the platform should cover.

      Value type: integer >= 0.

      0 = only the center chunk (1x1 chunks)       -> 16x16 blocks
      1 = center chunk + 1 in each direction (3x3) -> 48x48 blocks
      2 = center chunk + 2 in each direction (5x5) -> 80x80 blocks
       ...etc. Formula: (2*chunk_radius + 1) x (2*chunk_radius + 1) chunks.

      Default value: 1
      """,
    PropertyKey.integer("platform.chunk_radius", 1)
  ),

  /**
   * Material used for the main floor of the platform.
   * <p>
   * Expects a valid {@link Material} name.
   *
   * @see Material
   */
  PLATFORM_MAIN_BLOCK(
    """
      The block that makes up the MAIN (filling) part of the platform.

      Value type: text (Bukkit material name).
      Format: UPPER_SNAKE_CASE.
      Examples: STONE, DIRT, GRASS_BLOCK, SAND, NETHERRACK, OBSIDIAN
      Full list: https://hub.spigotmc.org/javadocs/bukkit/org/bukkit/Material.html

      Default value: STONE
      Note: an invalid name = default value.
      """,
    PropertyKey.string("platform.main_block", "STONE")
  ),

  /**
   * Material used for the border (edge) of the platform.
   *
   * @see Material
   */
  PLATFORM_BORDER_BLOCK(
    """
      The block used for the BORDER / pattern on the platform.
      Its exact meaning depends on the "pattern" setting (see below).

      Value type: text (Bukkit material name).
      Format: UPPER_SNAKE_CASE.
      Examples: BEDROCK, GLOWSTONE, SEA_LANTERN, QUARTZ_BLOCK
      Full list: https://hub.spigotmc.org/javadocs/bukkit/org/bukkit/Material.html

      Default value: BEDROCK
      Note: an invalid name = default value.
      """,
    PropertyKey.string("platform.border_block", "BEDROCK")
  ),

  /**
   * Shape / style of the generated platform.
   *
   * @see PlatformBorderPattern
   */
  PLATFORM_PATTERN(
    """
      The shape / pattern of the platform. This determines how
      main_block and border_block are arranged.

      Value type: one of four values (exactly, uppercase):

         SPAWN_MARKER - at the spawn point (x/z from the [spawn] section)
                        ONLY 4 blocks of border_block are generated,
                        and ALL the rest of the platform is main_block.
                        Effect: a small marker at the spawn point.

         RING         - a border / ring along the outer edge
                        of the platform made of border_block, and the
                        center (inside the ring) ENTIRELY of main_block.
                        Effect: a frame around the center.

         FULL         - the ENTIRE square platform (within chunk_radius)
                        built EXCLUSIVELY of border_block.
                        Effect: a solid slab of the border block.

         NONE         - the ENTIRE platform (within chunk_radius) built
                        EXCLUSIVELY of main_block. No border or pattern.
                        Effect: a smooth floor with no pattern.

      Default value: SPAWN_MARKER
      Note: an invalid name = default value.
      """,
    PropertyKey.enumeration("platform.pattern", PlatformBorderPattern.class, PlatformBorderPattern.SPAWN_MARKER)
  ),

  /**
   * Whether the fixed spawn point defined by {@link #SPAWN_X},
   * {@link #SPAWN_Y}, {@link #SPAWN_Z}, {@link #SPAWN_YAW} and
   * {@link #SPAWN_PITCH} should be used.
   * <p>
   * When {@code false}, vanilla spawn-selection logic is used instead.
   */
  SPAWN_ENABLED(
    """
      Whether to force a fixed spawn point for all players.

      true  = every player appears exactly at the coordinates
               spawn.x / spawn.y / spawn.z with yaw/pitch orientation
      false = default Minecraft spawn logic is used
               (x/y/z/yaw/pitch settings are ignored)

      Default value: true
      """,
    PropertyKey.bool("spawn.enabled", true)
  ),

  /**
   * X coordinate of the fixed spawn point (east / west axis).
   * <p>
   * A value of {@code 0.0} places the player in the exact middle of block
   * {@code 0}.
   */
  SPAWN_X(
    """
      The X coordinate of the spawn point (east-west axis).

      Value type: floating-point number (e.g. 0.0, 12.5, -30.0).
      0.0 = exact center of the block with X = 0.
      Integer value (e.g. 10.0) = center of block X=10.
      Value with .5 (e.g. 10.5) = boundary between blocks 10 and 11.

      Default value: 0.0
      """,
    PropertyKey.decimal("spawn.x", 0.0D)
  ),

  /**
   * Y coordinate of the fixed spawn point (height).
   * <p>
   * The default of {@code 65.0} places the player one block above a platform
   * generated at {@link #PLATFORM_Y y=64}.
   */
  SPAWN_Y(
    """
      The Y coordinate of the spawn point (height).

      Value type: floating-point number.
      Tip: if the platform is at y=64 (the top surface of the block
            is 64 + 1 = 65.0), then for the player to STAND on the
            platform, set spawn.y = 65.0.
      Value 65.0 = one block above the block at Y=64.

      Default value: 65.0
      """,
    PropertyKey.decimal("spawn.y", 65.0D)
  ),

  /**
   * Z coordinate of the fixed spawn point (north / south axis).
   * <p>
   * A value of {@code 0.0} places the player in the exact middle of block
   * {@code 0}.
   */
  SPAWN_Z(
    """
      The Z coordinate of the spawn point (north-south axis).

      Value type: floating-point number.
      Works exactly like spawn.x, just on the Z axis.

      Default value: 0.0
      """,
    PropertyKey.decimal("spawn.z", 0.0D)
  ),

  /**
   * Yaw of the fixed spawn point, in degrees (left / right rotation).
   * <p>
   * {@code 0} faces south, {@code 90} faces west, {@code 180} faces north
   * and {@code 270} faces east.
   */
  SPAWN_YAW(
    """
      The player's horizontal rotation (left / right), in degrees.

      Value type: floating-point number (degrees).
      0   = player faces south
      90  = player faces west
      180 = player faces north
      270 = player faces east
      Intermediate values are also allowed (e.g. 45 = south-west).

      More info: https://minecraft.wiki/w/Rotation
      Default value: 0.0
      """,
    PropertyKey.floatKey("spawn.yaw", 0.0F)
  ),

  /**
   * Pitch of the fixed spawn point, in degrees (up / down rotation).
   * <p>
   * {@code -90} looks straight up, {@code 0} looks straight ahead and
   * {@code 90} looks straight down.
   */
  SPAWN_PITCH(
    """
      The player's vertical rotation (looking up / down), in degrees.

      Value type: floating-point number (degrees).
        -90 = player looks straight UP
          0 = player looks straight AHEAD
         90 = player looks straight DOWN

      More info: https://minecraft.wiki/w/Rotation
      Default value: 0.0
      """,
    PropertyKey.floatKey("spawn.pitch", 0.0F)
  ),

  METRICS_ENABLED(
    """
      Whether the plugin may send anonymous statistics (bStats).

      true  = statistics are sent
      false = statistics are NOT sent

      Statistics are fully anonymous and are used only to collect
      information about plugin popularity and server versions.

      Default value: true
      """,
    PropertyKey.bool("metrics.enabled", true)
  ),
  ;

  private final String comment;
  private final PropertyKey<?> key;

  SettingsKeys(final String comment, final PropertyKey<?> key) {
    this.comment = comment;
    this.key = key;
  }

  @Override
  public String comment() {
    return this.comment;
  }

  @Override
  public PropertyKey<?> key() {
    return this.key;
  }
}